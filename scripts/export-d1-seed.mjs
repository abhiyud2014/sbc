/**
 * Export the local node:sqlite database to a D1 seed file.
 *
 *   node scripts/export-d1-seed.mjs
 *
 * Output: worker/seed.sql
 *
 * WARNING: the export contains student names/emails and scrypt password
 * hashes. Never commit it to a public repository. `worker/seed.sql` is
 * git-ignored for exactly that reason.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DatabaseSync } from 'node:sqlite';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const source = process.env.DB_PATH || path.join(root, 'server', 'sbc.db');
const dest = path.join(root, 'worker', 'seed.sql');

// Parent tables first so foreign keys are satisfied.
const TABLES = [
  'batches',
  'students',
  'student_batches',
  'meeting_targets',
  'meeting_target_batches',
  'registrations',
  'questions',
  'knowledge',
  'chat_conversations',
  'chat_messages',
  'materials',
  'admins',
  'settings',
];

const sqlValue = (value) => {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'NULL';
  if (typeof value === 'bigint') return value.toString();
  if (typeof value === 'boolean') return value ? '1' : '0';
  if (value instanceof Uint8Array) return `X'${Buffer.from(value).toString('hex')}'`;
  return `'${String(value).replace(/'/g, "''")}'`;
};

const quote = (name) => `"${String(name).replace(/"/g, '""')}"`;

if (!fs.existsSync(source)) {
  console.error(`Database not found: ${source}`);
  process.exit(1);
}

const db = new DatabaseSync(source);
const lines = [
  '-- Generated by scripts/export-d1-seed.mjs from server/sbc.db.',
  '-- WARNING: contains personal data and password hashes. DO NOT COMMIT.',
  '-- Apply with:',
  '--   wrangler d1 execute sbc-lms --remote --file=worker/seed.sql',
  '',
];

let total = 0;
for (const table of TABLES) {
  let columns;
  try {
    columns = db.prepare(`PRAGMA table_info(${quote(table)})`).all().map((c) => c.name);
  } catch (err) {
    console.warn(`Skipping ${table}: ${err.message}`);
    continue;
  }
  if (!columns.length) {
    console.warn(`Skipping ${table}: no columns (table missing?)`);
    continue;
  }
  const rows = db.prepare(`SELECT * FROM ${quote(table)}`).all();
  if (!rows.length) continue;
  lines.push(`-- ${table}: ${rows.length} row(s)`);
  const columnList = columns.map(quote).join(', ');
  for (const row of rows) {
    const values = columns.map((column) => sqlValue(row[column])).join(', ');
    lines.push(`INSERT OR REPLACE INTO ${quote(table)} (${columnList}) VALUES (${values});`);
    total += 1;
  }
  lines.push('');
}

db.close();

fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, `${lines.join('\n')}\n`, 'utf8');
console.log(`Wrote ${total} rows to ${path.relative(root, dest)}`);
console.log('Remember: this file is git-ignored because it contains private data.');
